import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../public/', import.meta.url));
async function files(dir = root) {
  const entries = await readdir(dir, { withFileTypes: true });
  return (await Promise.all(entries.map((entry) => entry.isDirectory() ? files(path.join(dir, entry.name)) : path.join(dir, entry.name)))).flat();
}
// Source archives are offered separately; the offline runtime does not need them.
const assets = (await files()).filter((file) => !file.endsWith('/sw.js') && !path.relative(root, file).startsWith('source/')).sort();
const template = await readFile(new URL('./service-worker.js', import.meta.url), 'utf8');
const hash = createHash('sha256').update(template);
const manifest = [];
for (const file of assets) {
  const bytes = await readFile(file);
  const name = path.relative(root, file);
  hash.update(name); hash.update(bytes);
  manifest.push({ path: './' + name, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') });
}
const index = manifest.find(asset => asset.path === './index.html');
manifest.unshift({ ...index, path: './' });
const version = hash.digest('hex').slice(0, 16);
const source = '// Generated by scripts/build-cache.mjs. Do not edit by hand.\n' + template
  .replace('__CACHE_VERSION__', version).replace('__ASSET_MANIFEST__', JSON.stringify(manifest, null, 2));
await writeFile(path.join(root, 'sw.js'), source);
console.log(`Offline cache ${version}: ${manifest.length} assets, ${manifest.reduce((sum, asset) => sum + asset.bytes, 0)} bytes`);
