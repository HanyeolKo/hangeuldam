import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../public/', import.meta.url));
async function files(dir = root) {
  const entries = await readdir(dir, { withFileTypes: true });
  return (await Promise.all(entries.map((entry) => entry.isDirectory() ? files(path.join(dir, entry.name)) : path.join(dir, entry.name)))).flat();
}
// Source archives are offered separately; the offline runtime does not need them.
const assets = (await files()).filter((file) => !file.endsWith('/sw.js') && !path.relative(root, file).startsWith('source/')).sort();
const hash = createHash('sha256');
for (const file of assets) { hash.update(path.relative(root, file)); hash.update(await readFile(file)); }
const version = hash.digest('hex').slice(0, 16);
const list = ['./', ...assets.map((file) => './' + path.relative(root, file))];
const source = `// Generated by scripts/build-cache.mjs. Do not edit by hand.
const PREFIX = 'hangeuldam-' + new URL(self.registration.scope).pathname + '-';
const CACHE = PREFIX + '${version}';
const ASSETS = ${JSON.stringify(list, null, 2)};
const FEATURES = ['edit-hwp-v2', 'device-ui-v3'];
const urls = ASSETS.map(p => new URL(p, self.registration.scope).href);
async function prepare() {
  const cache = await caches.open(CACHE);
  let complete = 0;
  for (const url of urls) {
    if (!(await cache.match(url))) {
      const response = await fetch(new Request(url, { cache: 'reload', credentials: 'same-origin' }));
      if (!response.ok) throw new Error('오프라인 파일 저장에 실패했습니다.');
      await cache.put(url, response);
    }
    complete++;
    if (complete % 8 === 0 || complete === urls.length) {
      for (const client of await self.clients.matchAll({ includeUncontrolled: true })) client.postMessage({ type: 'HANGEULDAM_CACHE_PROGRESS', complete, total: urls.length });
    }
  }
}
self.addEventListener('install', event => event.waitUntil(prepare().then(() => self.skipWaiting())));
self.addEventListener('activate', event => event.waitUntil((async () => {
  for (const key of await caches.keys()) if (key.startsWith(PREFIX) && key !== CACHE) await caches.delete(key);
  await self.clients.claim();
})()));
self.addEventListener('message', event => {
  if (event.data?.type === 'STATUS') event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    const ready = (await Promise.all(urls.map(url => cache.match(url)))).every(Boolean);
    event.ports[0]?.postMessage({ ready, features: FEATURES, version: CACHE });
  })());
  if (event.data?.type === 'PREPARE') event.waitUntil(prepare().then(
    () => event.ports[0]?.postMessage({ ready: true }),
    error => event.ports[0]?.postMessage({ error: error.message })
  ));
});
self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin || !url.href.startsWith(self.registration.scope)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const found = await cache.match(event.request, { ignoreSearch: true });
    if (found) return found;
    try { return await fetch(event.request); }
    catch (error) {
      if (event.request.mode === 'navigate') return await cache.match(self.registration.scope) || Response.error();
      throw error;
    }
  })());
});
`;
await writeFile(path.join(root, 'sw.js'), source);
console.log(`Offline cache ${version}: ${list.length} assets`);
